  APP_ID   NUMBER(3) NOT NULL,
  MENU_ID  NUMBER(5) NOT NULL,
  CONSTRAINT PK_M_OTORISASI_PNC PRIMARY KEY (LOGIN_ID_GROUP, APP_ID, MENU_ID)
